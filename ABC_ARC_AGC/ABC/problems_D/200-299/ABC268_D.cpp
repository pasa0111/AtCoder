    ll n,m; cin >> n >> m;
    vector<string> S(n); vecin(S);

    constexpr ll base = 370610274;
    auto hash = [&](string& X){
        mint t1 = 1, h1 = 0;
        Mint t2 = 1, h2 = 0;
        for(char c:X){
            h1 += t1*c;
            h2 += t2*c;
            t1 *= base;
            t2 *= base;
        }
        return pair(h1.val(),h2.val());
    };

    set<pair<ll,ll>> H;
    rep(i,m){
        string T; cin >> T;
        H.insert(hash(T));
    }

    string ans = "";
    vector<ll> P(n);
    auto dfs = [&](this auto&& dfs, string X, ll i){
        if(!ans.empty()) return;
        X += S[P[i]];
        if(i == n-1){
            if(!(3 <= X.size() && X.size() <= 16)) return;
            else if(!H.count(hash(X))) ans = X;
            return;
        }

        for(ll cnt = 1; X.size()+cnt < 16; cnt++){
            dfs(X+string(cnt,'_'),i+1);
        }
        return;
    };

    for(ll i = 0; i < n; i++) P[i] = i;
    do{
        dfs("",0);
        if(!ans.empty()) break;
    }while(next_permutation(P.begin(), P.end()));

    if(ans.empty()) cout << -1 << el;
    else cout << ans << el;
